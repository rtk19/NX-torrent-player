static std::string lower(std::string s)
{
    for (char& c : s) c = (char)std::tolower((unsigned char)c);
    return s;
}

std::string httpUrl(const std::string& url)
{
    auto colon = url.find(':');
    if (colon == std::string::npos) return {};
    auto scheme = lower(url.substr(0, colon));
    if (scheme != "http" && scheme != "https") return {};
    if (url.compare(colon, 3, "://") != 0) return {};
    auto authorityEnd = url.find_first_of("/?#", colon + 3);
    if (authorityEnd == colon + 3 || url.size() == colon + 3) return {};
    for (unsigned char c : url)
        if (c <= 32 || c == 127 || c == '\\') return {};
    return scheme + url.substr(colon, url.find('#') - colon);
}

std::vector<std::string> headerFields(const Headers& headers)
{
    std::vector<std::string> fields;
    std::vector<std::string> names;
    size_t bytes = 0;
    for (const auto& h : headers) {
        bool valid = !h.first.empty();
        for (unsigned char c : h.first)
            valid &= std::isalnum(c) || std::string("!#$%&'*+-.^_`|~").find(c) != std::string::npos;
        for (unsigned char c : h.second)
            valid &= (c >= 32 && c != 127) || c == '\t';
        auto name = lower(h.first);
        // These belong to the HTTP transport. An addon-supplied Range would
        // otherwise break resume/seek requests generated by FFmpeg.
        if (name == "range" || name == "content-length" || name == "transfer-encoding" ||
            name == "connection") valid = false;
        if (!valid || h.second.size() > 16384) continue;
        auto field = h.first + ": " + h.second;
        if (bytes + field.size() > 65536 || fields.size() >= 64) break;
        auto it = std::find(names.begin(), names.end(), name);
        if (it != names.end()) {
            auto index = (size_t)(it - names.begin());
            bytes -= fields[index].size();
            fields[index] = field;
        } else {
            names.push_back(name);
            fields.push_back(field);
        }
        bytes += field.size();
    }
    return fields;
}

Headers requestHeaders(const std::string& streamJson)
{
    auto hints = json::object(streamJson, "behaviorHints");
    auto proxy = json::object(hints, "proxyHeaders");
    return json::stringMembers(json::object(proxy, "request"));
}
